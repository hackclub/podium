// Builds seed.sql from event-sizes.csv: one fake Haven event per row, with
// that many participants and staff on its roster. Rows are generated inside
// Postgres with generate_series, so the SQL stays a few KB.
//
// Emails are deterministic so k6 can derive users without a lookup:
//   participant j of event i  ->  p-<i>-<j>@loadtest.invalid
//   staff j of event i        ->  s-<i>-<j>@loadtest.invalid (s-<i>-1 is POC)
//   superadmin                ->  admin@loadtest.invalid
// Event i has slug lt-<i>. Event 1 is the largest (the CSV is sorted).
//
//   node loadtest/gen-seed.mjs > loadtest/seed.sql
import { readFileSync } from 'node:fs';

const rows = readFileSync(new URL('./event-sizes.csv', import.meta.url), 'utf8')
  .trim()
  .split('\n')
  .slice(1)
  .map((line, i) => {
    const [tz, format, participants, staff] = line.split(',');
    return `(${i + 1}, ${Number(tz)}, '${format}', ${Number(participants)}, ${Number(staff)})`;
  });

console.log(`-- Generated by loadtest/gen-seed.mjs. Only run against the loadtest database.
BEGIN;

CREATE TEMP TABLE sizes (idx int, tz int, format text, p int, s int) ON COMMIT DROP;
INSERT INTO sizes VALUES
${rows.join(',\n')};

INSERT INTO users (email, first_name, display_name, is_admin, is_superadmin)
VALUES ('admin@loadtest.invalid', 'Admin', 'Loadtest Admin', true, true);

INSERT INTO users (email, first_name, last_name, display_name)
SELECT format('p-%s-%s@loadtest.invalid', idx, j), 'P' || j, 'E' || idx, format('Participant %s-%s', idx, j)
FROM sizes, generate_series(1, p) j
UNION ALL
SELECT format('s-%s-%s@loadtest.invalid', idx, j), 'S' || j, 'E' || idx, format('Staff %s-%s', idx, j)
FROM sizes, generate_series(1, s) j;

-- Same shape the Haven importer creates (haven.service.ts), but already enabled.
INSERT INTO events (name, slug, description, enabled, feature_flags_csv,
                    theme_name, theme_font, theme_primary, theme_selected, owner_id, poc_id)
SELECT 'Loadtest ' || idx, 'lt-' || idx, format('%s game jam (UTC%s)', format, tz), true,
       'haven,roster-only,itch-required', 'haven', '', '', '',
       (SELECT id FROM users WHERE email = 'admin@loadtest.invalid'),
       (SELECT id FROM users WHERE email = format('s-%s-1@loadtest.invalid', idx))
FROM sizes;

INSERT INTO event_attendees (event_id, user_id)
SELECT e.id, u.id
FROM users u
JOIN events e ON e.slug = 'lt-' || split_part(split_part(u.email, '@', 1), '-', 2)
WHERE u.email ~ '^[ps]-[0-9]+-[0-9]+@loadtest\\.invalid$';

COMMIT;

SELECT (SELECT count(*) FROM events) AS events,
       (SELECT count(*) FROM users) AS users,
       (SELECT count(*) FROM event_attendees) AS attendees;`);
